from solution import free_slots

# 2024-01-01 is a Monday; 2024-01-06/07 are Saturday/Sunday; 2024-02-29 is a Thursday.


def _raises(*args, **kwargs):
    try:
        free_slots(*args, **kwargs)
    except ValueError:
        return True
    return False


def test_example_from_spec():
    busy = [("2024-01-01T10:00", "2024-01-01T11:00"), ("2024-01-01T10:30", "2024-01-01T12:15"),
            ("2024-01-01T16:40", "2024-01-02T09:20")]
    assert free_slots(busy, "2024-01-01T00:00", "2024-01-02T12:00", min_minutes=45) == [
        ("2024-01-01T09:00", "2024-01-01T10:00"), ("2024-01-01T12:15", "2024-01-01T16:40"),
        ("2024-01-02T09:20", "2024-01-02T12:00")]


def test_no_busy_gives_whole_working_periods():
    assert free_slots([], "2024-01-01T00:00", "2024-01-03T00:00") == [
        ("2024-01-01T09:00", "2024-01-01T17:00"), ("2024-01-02T09:00", "2024-01-02T17:00")]


def test_unsorted_overlapping_and_touching_busy():
    busy = [("2024-01-02T14:00", "2024-01-02T15:00"), ("2024-01-02T09:30", "2024-01-02T10:00"),
            ("2024-01-02T13:00", "2024-01-02T14:00"), ("2024-01-02T09:45", "2024-01-02T11:00"),
            ("2024-01-02T15:00", "2024-01-02T16:00")]
    assert free_slots(busy, "2024-01-02T00:00", "2024-01-03T00:00", min_minutes=15) == [
        ("2024-01-02T09:00", "2024-01-02T09:30"), ("2024-01-02T11:00", "2024-01-02T13:00"),
        ("2024-01-02T16:00", "2024-01-02T17:00")]


def test_min_minutes_is_inclusive():
    busy = [("2024-01-03T09:30", "2024-01-03T12:00"), ("2024-01-03T12:29", "2024-01-03T17:00")]
    assert free_slots(busy, "2024-01-03T00:00", "2024-01-04T00:00", min_minutes=30) == [
        ("2024-01-03T09:00", "2024-01-03T09:30")]
    assert free_slots(busy, "2024-01-03T00:00", "2024-01-04T00:00", min_minutes=29) == [
        ("2024-01-03T09:00", "2024-01-03T09:30"), ("2024-01-03T12:00", "2024-01-03T12:29")]
    assert free_slots(busy, "2024-01-03T00:00", "2024-01-04T00:00", min_minutes=31) == []


def test_busy_spanning_days_and_window_edges():
    busy = [("2024-01-01T15:00", "2024-01-03T10:00")]
    assert free_slots(busy, "2024-01-01T11:30", "2024-01-04T12:00") == [
        ("2024-01-01T11:30", "2024-01-01T15:00"), ("2024-01-03T10:00", "2024-01-03T17:00"),
        ("2024-01-04T09:00", "2024-01-04T12:00")]


def test_weekends():
    window = ("2024-01-05T00:00", "2024-01-09T00:00")
    assert free_slots([], *window) == [("2024-01-05T09:00", "2024-01-05T17:00"),
                                       ("2024-01-08T09:00", "2024-01-08T17:00")]
    assert free_slots([], *window, weekdays_only=False) == [
        ("2024-01-05T09:00", "2024-01-05T17:00"), ("2024-01-06T09:00", "2024-01-06T17:00"),
        ("2024-01-07T09:00", "2024-01-07T17:00"), ("2024-01-08T09:00", "2024-01-08T17:00")]


def test_buffer_widens_busy_both_sides():
    busy = [("2024-01-02T08:30", "2024-01-02T08:50"), ("2024-01-02T12:00", "2024-01-02T13:00"),
            ("2024-01-02T17:10", "2024-01-02T18:00")]
    assert free_slots(busy, "2024-01-02T00:00", "2024-01-03T00:00", buffer=15) == [
        ("2024-01-02T09:05", "2024-01-02T11:45"), ("2024-01-02T13:15", "2024-01-02T16:55")]


def test_buffer_can_close_gaps():
    busy = [("2024-01-02T10:00", "2024-01-02T11:00"), ("2024-01-02T11:20", "2024-01-02T12:00")]
    assert free_slots(busy, "2024-01-02T09:00", "2024-01-02T13:00", buffer=10, min_minutes=1) == [
        ("2024-01-02T09:00", "2024-01-02T09:50"), ("2024-01-02T12:10", "2024-01-02T13:00")]


def test_zero_length_busy_is_ignored():
    busy = [("2024-01-02T12:00", "2024-01-02T12:00")]
    assert free_slots(busy, "2024-01-02T00:00", "2024-01-03T00:00", buffer=30) == [
        ("2024-01-02T09:00", "2024-01-02T17:00")]


def test_full_day_workday_ends_at_midnight_and_days_do_not_merge():
    busy = [("2024-01-06T22:00", "2024-01-07T01:00")]
    got = free_slots(busy, "2024-01-06T20:00", "2024-01-08T00:00", workday=("00:00", "24:00"), weekdays_only=False)
    assert got == [("2024-01-06T20:00", "2024-01-06T22:00"), ("2024-01-07T01:00", "2024-01-08T00:00")]
    got = free_slots([], "2024-01-06T23:00", "2024-01-07T02:00", workday=("00:00", "24:00"), weekdays_only=False)
    assert got == [("2024-01-06T23:00", "2024-01-07T00:00"), ("2024-01-07T00:00", "2024-01-07T02:00")]


def test_leap_day_and_month_boundaries():
    assert free_slots([], "2024-02-28T16:00", "2024-03-01T10:00", workday=("08:00", "18:00")) == [
        ("2024-02-28T16:00", "2024-02-28T18:00"), ("2024-02-29T08:00", "2024-02-29T18:00"),
        ("2024-03-01T08:00", "2024-03-01T10:00")]
    assert free_slots([], "2023-12-29T12:00", "2024-01-02T00:00") == [
        ("2023-12-29T12:00", "2023-12-29T17:00"), ("2024-01-01T09:00", "2024-01-01T17:00")]


def test_empty_window():
    assert free_slots([], "2024-01-02T10:00", "2024-01-02T10:00") == []
    assert free_slots([], "2024-01-02T18:00", "2024-01-02T20:00") == []


def test_malformed_timestamps():
    for bad in ["2024-1-05T09:00", "2024-01-5T09:00", "2024-01-05T9:00", "2024-01-05 09:00", "2024-01-05T09:00:00",
                "2024-02-30T10:00", "2023-02-29T10:00", "2024-01-05T24:00", "2024-01-05T09:60", "2024-13-01T09:00",
                "2024-01-05T09:00Z", " 2024-01-05T09:00", "2024-01-05t09:00", "+024-01-05T09:00"]:
        assert _raises([], bad, "2024-02-01T00:00"), bad
        assert _raises([], "2023-01-01T00:00", bad), bad
        assert _raises([(bad, "9999-12-31T23:59")], "2024-01-01T00:00", "2024-01-03T00:00"), bad
        assert _raises([("0001-01-01T00:00", bad)], "2024-01-01T00:00", "2024-01-03T00:00"), bad


def test_malformed_workday():
    w = ("2024-01-02T00:00", "2024-01-03T00:00")
    for bad in [("9:00", "17:00"), ("09:00", "17:0"), ("09-00", "17:00"), ("24:00", "24:00"), ("09:00", "24:01"),
                ("09:00", "25:00"), ("17:00", "09:00"), ("09:00", "09:00"), ("09:00 ", "17:00")]:
        assert _raises([], *w, workday=bad), bad
    assert free_slots([], *w, workday=("23:30", "24:00")) == [("2024-01-02T23:30", "2024-01-03T00:00")]


def test_other_errors():
    w = ("2024-01-02T00:00", "2024-01-03T00:00")
    assert _raises([("2024-01-02T11:00", "2024-01-02T10:59")], *w)
    assert _raises([], "2024-01-02T00:01", "2024-01-02T00:00")
    assert _raises([], *w, min_minutes=0)
    assert _raises([], *w, buffer=-1)
    assert free_slots([], *w, min_minutes=1, buffer=0) == [("2024-01-02T09:00", "2024-01-02T17:00")]
